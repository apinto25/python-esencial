ciudades = ["Bogotá", "Medellín", "Cali", "Barranquilla"]

# Iterando sobre una lista
for ciudad in ciudades:
    if ciudad == "Cali":
        continue
    print(ciudad)

# Iterando sobre un string
for letra in "Cali":
    print(letra)

# Iterando sobre un rango
for numero in range(1, 5):
    print(numero)
